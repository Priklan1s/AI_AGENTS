from langchain_ollama import OllamaLLM

llm = OllamaLLM(model="deepseek-coder:6.7b")

def requirement_agent(state):

    requirements = state["requirements"]

    prompt = f"""
Ты Senior QA Analyst.

Изучи приложенное требование, смежные документы и макеты в рамках текущего проекта.

Опирайся только на загруженные материалы и уже накопленный контекст проекта.

Нужно:

1) найти пробелы, противоречия и неоднозначности;

2) сравнить новую логику со смежными требованиями;

3) проверить полноту по принципам качественных требований;

4) подготовить вопросы для аналитика в формате: фрагмент -> риск -> вопрос.

Не придумывай поведение системы. Все неподтвержденные выводы помечай как гипотезу.
Требования:
{requirements}
"""

    result = llm.invoke(prompt)

    return {
        "analysis": result
    }